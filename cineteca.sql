-- Schema e dati di partenza della cineteca del corso FastAPI.
-- È uno script di reset: cancella lo schema cineteca (con tutto quello che contiene, qualunque
-- struttura abbia) e lo ricrea da zero con le sette tabelle e i dati iniziali, con gli id da 1.
-- Si può rilanciare in qualsiasi momento.

DROP SCHEMA IF EXISTS cineteca CASCADE;
CREATE SCHEMA cineteca;

CREATE TABLE cineteca.rooms (
    room_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code varchar(10) NOT NULL UNIQUE,
    name varchar(50) NOT NULL,
    seats integer NOT NULL CONSTRAINT rooms_seats_check CHECK (seats > 0)
);

CREATE TABLE cineteca.directors (
    director_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(100) NOT NULL UNIQUE
);

CREATE TABLE cineteca.movies (
    movie_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title varchar(200) NOT NULL,
    director_id integer NOT NULL REFERENCES cineteca.directors (director_id),
    release_year integer NOT NULL,
    runtime_min integer NOT NULL,
    purchase_price_eur integer NOT NULL,
    plot text,
    CONSTRAINT movies_title_release_year_key UNIQUE (title, release_year)
);

CREATE TABLE cineteca.actors (
    actor_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(100) NOT NULL
);

CREATE TABLE cineteca.movie_actors (
    movie_id integer NOT NULL REFERENCES cineteca.movies (movie_id) ON DELETE CASCADE,
    actor_id integer NOT NULL REFERENCES cineteca.actors (actor_id) ON DELETE CASCADE,
    character_name varchar(100) NOT NULL,
    PRIMARY KEY (movie_id, actor_id)
);

CREATE TABLE cineteca.screenings (
    screening_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    movie_id integer NOT NULL REFERENCES cineteca.movies (movie_id) ON DELETE CASCADE,
    room_id integer NOT NULL REFERENCES cineteca.rooms (room_id),
    starts_at timestamptz NOT NULL,
    ticket_price_eur numeric(5, 2) NOT NULL
);

CREATE TABLE cineteca.reviews (
    review_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    movie_id integer NOT NULL REFERENCES cineteca.movies (movie_id) ON DELETE CASCADE,
    author varchar(20) NOT NULL,
    rating integer NOT NULL CONSTRAINT reviews_rating_check CHECK (rating BETWEEN 1 AND 5),
    text varchar(500) NOT NULL,
    has_spoilers boolean NOT NULL DEFAULT false,
    created_at timestamptz NOT NULL DEFAULT now()
);

